use jobs;


DROP TABLE IF EXISTS ds_jobs;
DROP TABLE IF EXISTS companies;
DROP TABLE IF EXISTS countries;

CREATE TABLE companies (
    company_id   INT PRIMARY KEY,
    company_name VARCHAR(100) NOT NULL,
    industry     VARCHAR(50) NOT NULL
);

CREATE TABLE countries (
    country_id   INT PRIMARY KEY,
    country_name VARCHAR(50) NOT NULL UNIQUE,
    currency     VARCHAR(10) NOT NULL
);

CREATE TABLE ds_jobs (
    job_id            INT PRIMARY KEY,
    job_title         VARCHAR(100) NOT NULL,
    company_id        INT NOT NULL,
    country_id        INT NOT NULL,
    salary_usd        INT NOT NULL CHECK (salary_usd > 0),
    experience_level  VARCHAR(10) NOT NULL CHECK (experience_level IN ('Entry', 'Mid', 'Senior')),
    remote_type       VARCHAR(10) NOT NULL CHECK (remote_type IN ('Remote', 'Hybrid', 'Onsite')),
    years_experience  INT NOT NULL CHECK (years_experience >= 0),
    joining_year      INT NOT NULL,
    FOREIGN KEY (company_id) REFERENCES companies(company_id),
    FOREIGN KEY (country_id) REFERENCES countries(country_id)
);

